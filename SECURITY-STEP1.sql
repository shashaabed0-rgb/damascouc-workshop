-- مركز الدمشقي للصيانة - المرحلة 1: تأسيس الصلاحيات والجداول المحمية
-- إضافة فقط: لا يحذف ولا يعدّل shared_workspace أو بيانات الأجهزة الحالية.
-- شغّل هذا الملف مرة واحدة من Supabase SQL Editor بعد مراجعة التعليمات.
-- هذه المرحلة لا تقفل shared_workspace بعد؛ لا تعتبر التطبيق آمناً حتى استكمال ربط الواجهة ونقل البيانات واختبارها.

begin;

create table if not exists public.app_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'employee' check (role in ('admin','employee')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workshop_finance (
  id bigint generated by default as identity primary key,
  device_ref text,
  record_type text not null default 'note',
  amount numeric(12,2),
  description text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.workshop_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text not null default '',
  action text not null,
  entity_type text not null default '',
  entity_id text not null default '',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.app_profiles enable row level security;
alter table public.workshop_finance enable row level security;
alter table public.workshop_audit_log enable row level security;

-- دالة موثوقة للتحقق من دور المستخدم من قاعدة البيانات، وليس من كود المتصفح.
create or replace function public.is_workshop_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.app_profiles p
    where p.user_id = auth.uid()
      and p.role = 'admin'
  );
$$;

revoke all on function public.is_workshop_admin() from public, anon;
grant execute on function public.is_workshop_admin() to authenticated;

-- المستخدم يقرأ ملفه فقط، والمدير يقرأ ملفات الجميع.
drop policy if exists "workshop_profiles_read_self_or_admin" on public.app_profiles;
create policy "workshop_profiles_read_self_or_admin"
  on public.app_profiles for select to authenticated
  using (user_id = (select auth.uid()) or public.is_workshop_admin());

-- لا يستطيع أي مستخدم عادي إنشاء ملف صلاحيات أو تغيير دوره من الواجهة.
revoke all on table public.app_profiles from anon, authenticated;
grant select on table public.app_profiles to authenticated;

-- المالية: المدير فقط.
drop policy if exists "workshop_finance_admin_all" on public.workshop_finance;
create policy "workshop_finance_admin_all"
  on public.workshop_finance for all to authenticated
  using (public.is_workshop_admin())
  with check (public.is_workshop_admin());
revoke all on table public.workshop_finance from anon, authenticated;
grant select, insert, update, delete on table public.workshop_finance to authenticated;

-- سجل التدقيق: المدير يقرأه فقط في هذه المرحلة.
drop policy if exists "workshop_audit_admin_read" on public.workshop_audit_log;
create policy "workshop_audit_admin_read"
  on public.workshop_audit_log for select to authenticated
  using (public.is_workshop_admin());
revoke all on table public.workshop_audit_log from anon, authenticated;
grant select on table public.workshop_audit_log to authenticated;

-- كل حساب جديد يبدأ موظفاً. لا توجد ترقية تلقائية بناءً على البريد الإلكتروني.
create or replace function public.create_workshop_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.app_profiles (user_id, display_name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(new.email, ''), '@', 1)),
    'employee'
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

revoke all on function public.create_workshop_profile_for_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_workshop_profile on auth.users;
create trigger on_auth_user_created_workshop_profile
after insert on auth.users
for each row execute procedure public.create_workshop_profile_for_new_user();

-- إنشاء ملفات الحسابات الحالية كموظفين افتراضياً إن لم يكن لها ملف.
insert into public.app_profiles (user_id, display_name, role)
select
  u.id,
  coalesce(nullif(u.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(u.email, ''), '@', 1)),
  'employee'
from auth.users u
on conflict (user_id) do nothing;

-- ترقية الحسابين الموجودين حالياً اعتماداً على معرّف الحساب، وليس على بريد يرسله المتصفح.
update public.app_profiles
set role = 'admin', updated_at = now()
where user_id in (
  'f16afa35-10f6-41cf-852a-689993af4320'::uuid,
  'c7ee44f7-2bc3-49fa-a478-acff82e14fa1'::uuid
);

commit;

-- نتيجة تحقق بعد التنفيذ: يجب أن يظهر الحسابان المعتمدان بدور admin.
select u.email, p.role
from public.app_profiles p
join auth.users u on u.id = p.user_id
where u.id in (
  'f16afa35-10f6-41cf-852a-689993af4320'::uuid,
  'c7ee44f7-2bc3-49fa-a478-acff82e14fa1'::uuid
)
order by u.email;
